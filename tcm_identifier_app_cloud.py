def count_c_atoms(formula: Optional[str]) -> int:
    """计算分子式中的碳原子数"""
    if pd.isna(formula) or not formula:
        return 0
    match = re.search(r'C(\d+)', str(formula))
    return int(match.group(1)) if match else 0


def check_carbon_rt_correlation(carbon_count: int, rt: Optional[float], params: Dict = None) -> Tuple[float, str]:
    """检查碳数-RT相关性"""
    if params is None:
        params = DEFAULT_CARBON_RT_PARAMS

    if carbon_count <= 0 or pd.isna(rt):
        return 0.5, '无数据'

    for (c_min, c_max), p in params.items():
        if c_min <= carbon_count <= c_max:
            deviation = abs(rt - p['mean'])
            if deviation <= p['std']:
                return 1.0, '正常'
            elif deviation <= 2 * p['std']:
                return 0.5, '轻微偏离'
            elif rt > p['threshold']:
                return 0, '异常'
            else:
                return 0.3, '偏离'
    return 0.5, '超出范围'


def match_diagnostic_ions(compound_type: Optional[str], fragments_str: Optional[str], ion_library: Dict = None) -> Tuple[float, List[str]]:
    """匹配特征诊断离子"""
    if ion_library is None:
        ion_library = DEFAULT_DIAGNOSTIC_IONS

    if pd.isna(compound_type) or pd.isna(fragments_str):
        return 0, []

    matched_ions = []
    try:
        fragments = [float(x.strip()) for x in str(fragments_str).split(';') if x.strip() and x.strip() != 'nan']
    except:
        return 0, []

    for ctype, ions in ion_library.items():
        if ctype in str(compound_type):
            for frag in fragments:
                for ion in ions:
                    if abs(frag - ion) < 0.5:
                        matched_ions.append((ion, frag))
                        break

    if matched_ions:
        score = min(1.0, len(matched_ions) / 3)
        return score, [f'm/z {m[0]}(观测{m[1]:.1f})' for m in matched_ions[:5]]
    return 0, []


def analyze_neutral_losses(fragments_str: Optional[str], precursor_mz: Optional[float], loss_library: Dict = None) -> Tuple[List[str], List]:
    """分析中性丢失模式"""
    if loss_library is None:
        loss_library = DEFAULT_NEUTRAL_LOSSES

    if pd.isna(fragments_str) or pd.isna(precursor_mz):
        return [], []

    try:
        fragments = [float(x.strip()) for x in str(fragments_str).split(';') if x.strip() and x.strip() != 'nan']
    except:
        return [], []

    matches = []
    for loss_name, (loss_mass, description) in loss_library.items():
        for frag in fragments:
            neutral_loss = abs(precursor_mz - frag)
            if abs(neutral_loss - loss_mass) < 0.5:
                matches.append((loss_name, loss_mass, frag))

    if matches:
        return [f'{m[0]}(-{m[1]:.1f})' for m in matches[:3]], matches[:5]
    return [], []


def get_ppm_score(ppm: Optional[float]) -> Tuple[float, str]:
    """根据PPM值计算得分"""
    if pd.isna(ppm):
        return 0, '无数据'
    try:
        ppm_val = abs(float(ppm))
        if ppm_val < 5:
            return 1.0, f'{ppm_val:.2f}ppm (一级)'
        elif ppm_val < 10:
            return 0.85, f'{ppm_val:.2f}ppm (二级)'
        elif ppm_val < 20:
            return 0.70, f'{ppm_val:.2f}ppm (三级)'
        else:
            return 0.50, f'{ppm_val:.2f}ppm (四级)'
    except:
        return 0, '数据异常'


def calculate_confirmation_score(row: pd.Series, scoring_config: Dict = None) -> Dict:
    """计算单个化合物的确认评分"""
    if scoring_config is None:
        scoring_config = DEFAULT_SCORING_CONFIG

    detail = {
        '同位素得分': 0, '同位素说明': '',
        '双确认得分': 0, '双确认说明': '',
        '文献得分': 0, '文献说明': '',
        'PPM得分': 0, 'PPM说明': '',
        '碳RT得分': 0, '碳RT说明': '',
        '诊断离子得分': 0, '诊断离子匹配': '',
        '中性丢失': '',
        '总分': 0, '确认等级': '待验证', '优化建议': ''
    }

    # 1. PPM精度
    ppm_col = 'ppm'
    ppm_score, ppm_desc = get_ppm_score(row.get(ppm_col))
    detail['PPM得分'] = ppm_score * scoring_config['ppm_accuracy']
    detail['PPM说明'] = ppm_desc

    # 2. 文献支持
    lit_col = '库中文献数'
    lit_count = row.get(lit_col, 0)
    if pd.notna(lit_count) and int(lit_count) >= 3:
        detail['文献得分'] = scoring_config['literature_support']
        detail['文献说明'] = f'有 {int(lit_count)} 篇文献支持'
    else:
        detail['文献得分'] = int(lit_count) / 3 * scoring_config['literature_support'] if pd.notna(lit_count) else 0
        detail['文献说明'] = f'有 {int(lit_count) if pd.notna(lit_count) else 0} 篇文献支持'

    # 3. 正负离子双确认
    dual_col = '正负离子确认'
    double_confirmed = row.get(dual_col, '否')
    if double_confirmed == '是':
        detail['双确认得分'] = scoring_config['dual_ion_mode']
        detail['双确认说明'] = '双模式确认'
    else:
        detail['双确认说明'] = '单模式'

    # 4. 同位素匹配
    iso_col = '同位素峰匹配'
    iso_match = row.get(iso_col, '无')
    if pd.notna(iso_match) and str(iso_match) != '无' and str(iso_match) != '':
        detail['同位素得分'] = scoring_config['isotope_match']
        detail['同位素说明'] = f'匹配: {str(iso_match)[:30]}'
    else:
        detail['同位素说明'] = '无匹配'

    # 5. 碳数-RT相关性
    formula_col = '分子式'
    time_col = '出峰时间t/min'
    carbon_count = count_c_atoms(row.get(formula_col))
    rt = row.get(time_col)
    carbon_score, carbon_desc = check_carbon_rt_correlation(carbon_count, rt)
    detail['碳RT得分'] = carbon_score * scoring_config['carbon_rt_correlation']
    detail['碳RT说明'] = f'C{carbon_count}: {carbon_desc}'

    # 6. 特征诊断离子
    frag_col = '主要碎片离子'
    type_col = '化合物类型'
    ion_score, matched = match_diagnostic_ions(row.get(type_col), row.get(frag_col))
    detail['诊断离子得分'] = ion_score * scoring_config['diagnostic_ions']
    detail['诊断离子匹配'] = '; '.join(matched) if matched else ''

    # 7. 中性丢失分析
    mz_col = 'm/z实际值'
    neutral_losses, _ = analyze_neutral_losses(row.get(frag_col), row.get(mz_col))
    detail['中性丢失'] = ', '.join(neutral_losses[:3]) if neutral_losses else ''

    # 计算总分
    detail['总分'] = (
        detail['同位素得分'] + detail['双确认得分'] +
        detail['文献得分'] + detail['PPM得分'] +
        detail['碳RT得分'] + detail['诊断离子得分']
    )

    # 确定确认等级
    confirmation_levels = DEFAULT_CONFIRMATION_LEVELS
    if detail['总分'] >= confirmation_levels['高度确证']:
        detail['确认等级'] = '高度确证'
    elif detail['总分'] >= confirmation_levels['中度确证']:
        detail['确认等级'] = '中度确证'
    else:
        detail['确认等级'] = '待验证'

    # 生成优化建议
    suggestions = []
    if detail['同位素得分'] == 0:
        suggestions.append('建议进行同位素峰验证')
    if detail['双确认得分'] == 0:
        suggestions.append('建议补充另一种离子模式检测')
    if detail['文献得分'] < scoring_config['literature_support'] * 0.5:
        suggestions.append('增加文献支持')
    if detail['诊断离子得分'] == 0:
        suggestions.append('验证化合物类型特征诊断离子')

    detail['优化建议'] = '; '.join(suggestions) if suggestions else '无需补充'

    return detail


def add_confirmation_columns(df: pd.DataFrame, scoring_config: Dict = None) -> pd.DataFrame:
    """为DataFrame添加确认评分列"""
    if scoring_config is None:
        scoring_config = DEFAULT_SCORING_CONFIG

    results = []
    for _, row in df.iterrows():
        score_detail = calculate_confirmation_score(row, scoring_config)
        results.append(score_detail)

    score_df = pd.DataFrame(results)
    for col in score_df.columns:
        df[col] = score_df[col]

    return df


